'use strict';
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path'),assert=require('node:assert/strict');
const nodes=new Map(),node=id=>{if(!nodes.has(id))nodes.set(id,{textContent:'',classList:{toggle(){}}});return nodes.get(id);};
const src=fs.readFileSync(path.join(__dirname,'../static/monitor.js'),'utf8');
const ctx=vm.createContext({$:node,number:x=>typeof x==='number'&&Number.isFinite(x),ageText:x=>`Vor ${x} s`});
vm.runInContext(src.slice(src.indexOf('function renderDeviceStatus('),src.indexOf('function renderPrinter(')),ctx);
const draw=(readings,extra=0,connection='online')=>ctx.renderDeviceStatus({device_status:readings,stale_after_s:90},extra,connection);
const reading=value=>({value,age_s:0,current_session:true});const text=key=>node('device-'+key).textContent;
draw({fan_speed:reading(0),light_on:reading(false),box_fan_level:reading(2),speed_mode:reading(2)});
assert.equal(text('fan_speed'),'0 %');assert.equal(text('light_on'),'Aus');assert.equal(text('box_fan_level'),'Stufe 2');assert.equal(text('speed_mode'),'Standard');
draw({});assert.equal(text('fan_speed'),'Nicht gemeldet');assert.equal(text('light_on'),'Nicht gemeldet');
draw({speed_mode:reading(99)});assert.equal(text('speed_mode'),'Unbekannter Modus (99)');
draw({light_on:reading(true)},91);assert.match(text('light_on-age'),/Veraltet/);
draw({light_on:reading(true)},0,'offline');assert.match(text('light_on-age'),/Veraltet/);
draw({light_on:{...reading(true),current_session:false}});assert.match(text('light_on-age'),/Veraltet/);
draw({light_on:{value:false,age_s:-1}});assert.equal(text('light_on'),'Nicht gemeldet');
console.log('7 peripheral UI cases passed: real zero/off, missing fields, unknown mode, expiry, offline, reconnect, invalid age');
